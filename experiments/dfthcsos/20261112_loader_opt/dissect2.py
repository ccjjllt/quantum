"""Measure the *removable* Toffoli/CX classes in the Maoxin v22 loader family.

Symbolically replays each .kmx over the 11 selection bits (2048-point truth tables)
and reports, per circuit and in total:

  A. cache ANDs (ancilla CCX with two 1-bit controls) and duplicate monomials
  B. product CCX split by control-form type: identical forms (=> CX), constant-1
     form (=> CX), zero form (=> no-op), same-truth-table duplicates (=> cancel)
  C. exact algebraic duplicates on the same target (c1*c2 == c1'*c2')
  D. CX classes: self-CX (no-op), immediate inverse pairs, duplicate fanout edges
  E. monomial headroom: monomials generated by the product terms vs monomials the
     ANF actually needs (upper bound on rewrites that exploit m*m = m)

Usage: python dissect2.py [--dump PKL] path/to/kmx_dir
"""
from __future__ import annotations

import functools
import json
import pickle
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

N = 2048
ALL = (1 << N) - 1


def var_tt(i: int) -> int:
    period = 1 << i
    block = ((1 << period) - 1) << period
    out = 0
    for s in range(0, N, 2 * period):
        out |= block << s
    return out


VAR = [var_tt(i) for i in range(11)]


@functools.lru_cache(maxsize=None)
def anf(tt: int) -> tuple[int, ...]:
    """ANF monomial masks of a 2048-bit truth table (bit i = address i)."""
    x = [(tt >> i) & 1 for i in range(N)]
    bit = 1
    while bit < N:
        for base in range(0, N, bit << 1):
            for j in range(base + bit, base + 2 * bit):
                x[j] ^= x[j - bit]
        bit <<= 1
    return tuple(i for i, v in enumerate(x) if v)


def popcount1(m: int) -> int:
    return bin(m).count('1')


def parse(path: Path):
    lines = path.read_text().splitlines()
    names, regs = {}, {}
    for ln in lines:
        m = re.fullmatch(r'APPEND_TO_REGISTER q(\d+) r(\d+)', ln)
        if m:
            regs.setdefault(int(m.group(2)), []).append(int(m.group(1)))
        m = re.fullmatch(r'REGISTER r(\d+) "(\w+)"', ln)
        if m:
            names[int(m.group(1))] = m.group(2)
    qname = {}
    for rid, qs in regs.items():
        nm = names[rid]
        for i, q in enumerate(qs):
            qname[q] = f'sel{i}' if nm == 'selection' else f'w{nm[5:]}.{i}'
    nq = 0
    for ln in lines:
        for p in ln.split():
            if p.startswith('q'):
                nq = max(nq, int(p[1:]) + 1)
    return lines, qname, nq


def analyze(path: Path) -> dict:
    lines, qname, nq = parse(path)
    f = [0] * nq
    for q, nm in qname.items():
        if nm.startswith('sel'):
            f[q] = VAR[int(nm[3:])]
    cache_ands = []      # (qubit, mask, degree)
    live_mono = {}       # qubit -> mask
    products = []        # dict(i, c1, c2, t, f1, f2, tt)
    cxs = []             # (i, a, b, f_a, f_b_before)
    hist = Counter()
    for i, ln in enumerate(lines):
        parts = ln.split()
        if not parts or parts[0] in ('APPEND_TO_REGISTER', 'REGISTER'):
            continue
        g = parts[0]
        qs = [int(p[1:]) for p in parts[1:] if p.startswith('q')]
        hist[g] += 1
        if g == 'CX':
            a, b = qs
            if a == b:
                hist['CX_self'] += 1
            cxs.append((i, a, b, f[a], f[b]))
            f[b] ^= f[a]
            live_mono.pop(b, None)
        elif g == 'CCX':
            a, b, t = qs
            A, B = anf(f[a]), anf(f[b])
            tt = f[a] & f[b]
            if qname.get(t, '').startswith('w'):
                products.append(dict(i=i, c1=a, c2=b, t=t, tname=qname[t],
                                     f1=A, f2=B, tt=tt))
            else:
                if len(A) == 1 and len(B) == 1:
                    m = A[0] ^ B[0]
                    cache_ands.append((t, m, popcount1(m)))
                    live_mono[t] = m
                else:
                    hist['anc_ccx_wide'] += 1
            f[t] ^= tt
            live_mono.pop(t, None)
        elif g == 'X':
            for q in qs:
                f[q] = ~f[q] & ALL
        elif g in ('R', 'HMR'):
            for q in qs:
                f[q] = 0
                live_mono.pop(q, None)
        elif g in ('CZ', 'Z', 'CCZ', 'NEG'):
            pass
        else:
            raise SystemExit(f'unknown gate {g}: {ln}')
    final = {qname.get(q, f'q{q}'): f[q] for q in range(nq) if f[q]}
    return dict(path=str(path), nq=nq, hist=dict(hist), cache_ands=cache_ands,
                products=products, cxs=cxs, final=final)


def report(rec: dict) -> dict:
    name = Path(rec['path']).name
    cache = rec['cache_ands']
    prod = rec['products']
    out = {'name': name, 'ccx': rec['hist'].get('CCX', 0), 'cx': rec['hist'].get('CX', 0),
           'cache': len(cache), 'products': len(prod), 'q': rec['nq']}

    # ---- A. cache duplicates -------------------------------------------------
    masks = [m for _, m, _ in cache]
    out['cache_distinct'] = len(set(masks))
    out['cache_dup_pairs'] = len(masks) - len(set(masks))
    # same monomial cached again while it is still live elsewhere
    live, relive = set(), 0
    for _, m, _ in cache:
        if m in live:
            relive += 1
        live.add(m)
    out['cache_relive'] = relive
    out['cache_deg'] = dict(sorted(Counter(d for _, _, d in cache).items()))

    # ---- B. product control-form classes ------------------------------------
    cls = Counter()
    for p in prod:
        A, B = set(p['f1']), set(p['f2'])
        if not A or not B:
            cls['empty_form'] += 1
        elif A == B:
            cls['same_form'] += 1
        elif len(A) == 1 and p['f1'][0] == 0 and len(B) == 1 and p['f2'][0] == 0:
            cls['both_const1'] += 1
        elif (len(A) == 1 and p['f1'][0] == 0) or (len(B) == 1 and p['f2'][0] == 0):
            cls['one_const1'] += 1
        else:
            cls['generic'] += 1
    # truth-table duplicates on the same target: computing P twice cancels
    byt = defaultdict(list)
    for p in prod:
        byt[(p['t'], p['tt'])].append(p)
    dup_tt_pairs = sum(len(v) // 2 for v in byt.values() if len(v) > 1)
    out['prod_dup_tt_pairs'] = dup_tt_pairs
    out['prod_dup_tt_gates'] = sum(len(v) - len(v) % 2 for v in byt.values() if len(v) > 1)
    # exact same (c1,c2,target) function triple
    byf = defaultdict(list)
    for p in prod:
        key = (p['t'], frozenset(p['f1']), frozenset(p['f2']))
        byf[key].append(p)
    out['prod_dup_exact'] = sum(len(v) - 1 for v in byf.values() if len(v) > 1)
    out['prod_classes'] = dict(cls)

    # ---- D. CX classes ------------------------------------------------------
    cxs = rec['cxs']
    out['cx_self'] = sum(1 for _, a, b, _, _ in cxs if a == b)
    # immediate inverse pairs: identical CX with no intervening gate touching a or b
    gates = []
    for i, a, b, fa, fb in cxs:
        gates.append((i, a, b))
    idx = {i: k for k, (i, _, _) in enumerate(gates)}
    cancelled = 0
    state = {}  # (a,b) -> position in active stack of last occurrence
    # simple scan: track last occurrence of each (a,b) and whether any gate since
    # touched a or b
    last = {}
    live_keys = defaultdict(int)
    lastpos = {}
    for pos, (i, a, b) in enumerate(gates):
        # invalidate keys touching a or b
        for k in list(live_keys):
            if k[0] in (a, b) or k[1] in (a, b):
                del live_keys[k]
        k = (a, b)
        if k in live_keys:
            cancelled += 1
            del live_keys[k]
        else:
            live_keys[k] = pos
    out['cx_cancellable_pairs'] = cancelled
    # duplicate fanout edges (same source->target more than once, any distance)
    out['cx_dup_edge_pairs'] = sum(v - 1 for v in Counter((a, b) for _, a, b in gates).values() if v > 1)

    # ---- E. monomial headroom ----------------------------------------------
    need = Counter()
    for tname, tt in rec['final'].items():
        if tname.startswith('w'):
            for m in anf(tt):
                need[m] += 1
    gen = Counter()
    for p in prod:
        for m1 in p['f1']:
            for m2 in p['f2']:
                gen[m1 | m2] += 1
    out['anf_terms'] = sum(need.values())
    out['prod_monomial_terms'] = sum(gen.values())
    out['prod_monomial_distinct'] = len(gen)
    out['prod_mono_redundant'] = sum(gen.values()) - len(gen)
    return out


def main() -> None:
    args = [a for a in sys.argv[1:]]
    dump = None
    if '--dump' in args:
        k = args.index('--dump')
        dump = Path(args[k + 1])
        del args[k:k + 2]
    d = Path(args[0])
    rows = []
    recs = []
    for p in sorted(d.glob('angle_k_*.kmx'), key=lambda p: int(p.stem.split('_')[-1])):
        rec = analyze(p)
        recs.append(rec)
        rows.append(report(rec))
    tot = Counter()
    keys = ('ccx', 'cx', 'cache', 'products', 'cache_distinct', 'cache_dup_pairs',
            'cache_relive', 'prod_dup_tt_pairs', 'prod_dup_tt_gates', 'prod_dup_exact',
            'cx_self', 'cx_cancellable_pairs', 'cx_dup_edge_pairs', 'anf_terms',
            'prod_monomial_terms', 'prod_monomial_distinct', 'prod_mono_redundant')
    for r in rows:
        for k in keys:
            tot[k] += r.get(k, 0)
    print(f'{"k":>2} {"Q":>4} {"CCX":>5} {"CX":>6} {"cache":>5} {"dist":>4} {"dup":>3} '
          f'{"prod":>5} {"dupTT":>5} {"samef":>5} {"const1":>6} {"cxpair":>6}')
    for r in rows:
        c = r['prod_classes']
        print(f'{r["name"].split("_")[-1][:-4]:>2} {r["q"]:>4} {r["ccx"]:>5} {r["cx"]:>6} '
              f'{r["cache"]:>5} {r["cache_distinct"]:>4} {r["cache_dup_pairs"]:>3} '
              f'{r["products"]:>5} {r["prod_dup_tt_gates"]:>5} {c.get("same_form", 0):>5} '
              f'{c.get("one_const1", 0) + c.get("both_const1", 0):>6} {r["cx_cancellable_pairs"]:>6}')
    print('\nTOTALS', json.dumps({k: tot[k] for k in keys}, indent=1))
    print('product classes', json.dumps({k: tot[k] for k in ()}))
    classes = Counter()
    for r in rows:
        classes.update(r['prod_classes'])
    print('product class totals', dict(classes))
    print('\nper-circuit detail')
    for r in rows:
        print(json.dumps(r, sort_keys=True))
    if dump:
        dump.parent.mkdir(parents=True, exist_ok=True)
        with open(dump, 'wb') as fh:
            pickle.dump(recs, fh)
        print('dumped', dump)


if __name__ == '__main__':
    main()
